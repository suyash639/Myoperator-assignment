def run(cmd: list[str], timeout=600) -> tuple[int, str]:
    p = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout)
    return p.returncode, (p.stdout + p.stderr).strip()


def strip_code(md: str) -> str:
    return re.sub(r"```.*?```", "", re.sub(r"<!--.*?-->", "", md, flags=re.S), flags=re.S)


def source_tokens() -> tuple[set, set]:
    """Fractions and percentages present anywhere in validated source CSVs (outputs/*.csv, not outputs/final)."""
    fr, pc = set(), set()
    for p in OUT.glob("*.csv"):
        for r in csv.DictReader(p.open()):
            for a, b in (("numerator", "denominator"), ("affected_records", "denominator"), ("python_numerator", "python_denominator")):
                if r.get(a) not in (None, "") and r.get(b) not in (None, ""):
                    fr.add(f"{r[a]}/{r[b]}")
                    try:
                        if int(r[b]):
                            pc.add(f"{100 * int(r[a]) / int(r[b]):.1f}")
                    except ValueError:
                        pass
            for v in r.values():
                v = v or ""
                fr.update(f"{a}/{b}" for a, b in FRAC.findall(v))
                pc.update(x for x in PCT.findall(v))
                if re.fullmatch(r"0?\.\d+", v):
                    pc.add(f"{100 * float(v):.1f}")
    # Phase 1 validation tallies are recorded in the investigation log (INV-004), not in a CSV: accept fractions from it
    inv = Path("audit/investigation_log.md").read_text()
    fr.update(f"{a}/{b}" for a, b in FRAC.findall(inv))
    return fr, pc


