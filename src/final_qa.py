def reconcile(ids):
    cl, ew = claims(ids)
    docs = FINAL_MD + [FINAL_CSV]
    texts = {p.name: strip_code(p.read_text()) for p in docs}
    rows, fails = [], []
    for name, toks, src, kw in cl:
        cells, conflict = [], []
        frac_toks = [t for t in toks if "/" in t]
        for d, t in texts.items():
            present = [x for x in toks if (re.search(rf"(?<![\d./]){re.escape(x)}(?![\d/]|\.\d)", t) if x[0].isdigit() else x in t)]
            cells.append(", ".join(present) if present else "—")
            for line in t.splitlines():
                if not re.search(kw, line, re.I):
                    continue
                for a, b in FRAC.findall(line):
                    for ft in frac_toks:
                        fa, fb = ft.split("/")
                        if (b == fb and a != fa and re.search(rf"\b{a}/{b}\b", line)) and not any(
                                f"{a}/{b}" == other for other in source_frac):
                            conflict.append(f"{d}: {a}/{b}")
        ok = not conflict
        rows.append([name] + cells + [src, "PASS" if ok else "FAIL: " + "; ".join(sorted(set(conflict)))])
        if not ok:
            fails.append(name)
    # engineer-week rows in tables: '| **Bn**' rows must end with the allocated effort
    for p in FINAL_MD:
        for line in p.read_text().splitlines():
            m = re.match(r"^\|\s*\*\*(B[123])\*\*.*\|\s*([\d.]+)\s*\|\s*$", line)
            if m and float(m.group(2)) != ew[m.group(1)]:
                fails.append(f"{p.name}: {m.group(1)} effort {m.group(2)} != {ew[m.group(1)]}")
        for x in re.findall(r"(\d+(?:\.\d+)?) engineer-weeks", p.read_text()):
            if float(x) not in (6.0, 2.5, 2.0, 1.5, 0.5, 0.25, 1.0, 0.75):
                fails.append(f"{p.name}: unexpected engineer-week figure {x}")
    return [n.name for n in docs], rows, fails


