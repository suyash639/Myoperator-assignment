def sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def integrity():
    res = {}
    man = json.loads(Path("data/raw/manifest.json").read_text())
    mism = [t for t, e in man["tables"].items() if sha(Path("data/raw") / e["file"]) != e["sha256"]]
    res["raw_vs_manifest"] = (not mism, f"{len(man['tables'])} table files vs manifest; mismatches {mism or 'none'}")
    before = SCRATCH / "raw_before.sha"
    if before.exists():
        ref = dict(reversed(l.split()) for l in before.read_text().splitlines() if l.strip())
        diff = [n for n, h in ref.items() if sha(Path(n)) != h]
        res["raw_vs_pre_phase2_1"] = (not diff, f"{len(ref)} files vs hashes taken before Phase 2.1; differences {diff or 'none'}")
    else:
        res["raw_vs_pre_phase2_1"] = (None, "reference hash file not available (scratchpad cleared)")
    ro = all(not os.access(p, os.W_OK) for p in Path("data/raw").glob("*.json"))
    res["raw_read_only"] = (ro, "all data/raw/*.json read-only" if ro else "some raw files writable")
    p22 = SCRATCH / "p22"
    if p22.exists():
        diff = [f for f in P22_FILES if sha(p22 / f) != sha(OUT / f)]
        res["phase2_2_outputs"] = (not diff, f"{len(P22_FILES)} Phase 2.2 outputs vs copies taken after Phase 2.2; differences {diff or 'none'}; "
                                             + "; ".join(f"{f}={sha(OUT / f)[:12]}" for f in P22_FILES))
    else:
        res["phase2_2_outputs"] = (None, "reference copies not available")
    logs = sorted(Path("logs").glob("extraction_*.log"))
    res["airtable_calls"] = (len(logs) == 1 and len(man.get("runs", [])) == 1,
                             f"extraction logs: {[l.name for l in logs]}; manifest runs: {len(man.get('runs', []))}; "
                             "only src/extract.py constructs the Airtable client")
    users = sorted(str(p) for p in Path("src").glob("*.py")
                   if re.search(r"^\s*from src\.airtable_client import[^\n]*\bAirtableClient\b", p.read_text(), re.M))
    res["client_users"] = (users == ["src/extract.py"], f"modules importing the AirtableClient class: {users}")
    rc, out = run(["git", "log", "--oneline", "-1"])
    rc2, rem = run(["git", "remote", "-v"])
    res["git"] = ("does not have any commits" in out and rem == "", f"git log: '{out[:60]}'; remotes: '{rem or 'none'}'")
    return res


def pdf_check():
    from src.render_pdf import page_count
    out = {}
    for n in ("Executive_Product_Memo", "Q3_Product_Roadmap", "Metrics_Specification"):
        p, md = FINAL / "pdf" / f"{n}.pdf", FINAL / f"{n}.md"
        if not p.exists():
            out[n] = (False, "missing")
            continue
        fresh = p.stat().st_mtime >= md.stat().st_mtime
        pages = page_count(p)
        ok = fresh and (pages == 1 if n == "Executive_Product_Memo" else pages >= 1)
        out[n] = (ok, f"{pages} page(s); {'newer than' if fresh else 'OLDER than'} its Markdown source; {p.stat().st_size // 1024} KB")
    return out


