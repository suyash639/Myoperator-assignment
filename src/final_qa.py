def sensitive_scan():
    from src.data import load
    s = load()
    pii = {v for t in ("Candidates", "People") for f in s.f(t).values()
           for k in ("Full Name", "Email", "Work Email", "Phone") if (v := f.get(k))}
    token = ""
    if Path(".env").exists():
        for line in Path(".env").read_text().splitlines():
            if line.startswith("AIRTABLE_TOKEN="):
                token = line.split("=", 1)[1].strip().strip('"').strip("'")
    base_id = ""
    if Path(".env").exists():
        for line in Path(".env").read_text().splitlines():
            if line.startswith("AIRTABLE_BASE_ID="):
                base_id = line.split("=", 1)[1].strip().strip('"').strip("'")
    from src.airtable_client import token_fingerprint
    fp = token_fingerprint(token) if token else ""
    hits = []
    files = [p for p in FINAL.rglob("*") if p.is_file()]
    for p in files:
        b = p.read_bytes()
        txt = b.decode("utf-8", "ignore")
        if token and len(token) >= 20 and token.encode() in b:
            hits.append(f"{p.name}: configured token value")
        if re.search(r"pat[A-Za-z0-9]{14}\.[a-f0-9]{64}", txt):
            hits.append(f"{p.name}: PAT-shaped string")
        if fp and fp in txt:
            hits.append(f"{p.name}: token fingerprint")
        if base_id and base_id in txt:
            hits.append(f"{p.name}: Airtable base ID")
        if re.search(r"\(len \d+, `?pat`? prefix\)", txt):
            hits.append(f"{p.name}: token length/prefix metadata")
        if re.search(r"Bearer\s+[A-Za-z0-9._\-]{20,}", txt):
            hits.append(f"{p.name}: bearer header")
        if p.suffix in (".md", ".csv"):
            if re.search(r"[\w.+-]+@[\w-]+\.[a-z]{2,}", txt):
                hits.append(f"{p.name}: email-shaped string")
            if re.search(r"\+91[\s\d]{8,}", txt):
                hits.append(f"{p.name}: phone-shaped string")
            leaked = [x for x in pii if x in txt]
            if leaked:
                hits.append(f"{p.name}: {len(leaked)} personal values from the snapshot")
    return len(files), hits


