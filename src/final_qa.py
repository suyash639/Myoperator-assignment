def number_trace(fr, pc):
    out = {}
    for p in FINAL_MD + [FINAL_CSV]:
        t = strip_code(p.read_text())
        bad_f = sorted({f"{a}/{b}" for a, b in FRAC.findall(t)} - fr)
        bad_p = sorted({x for x in PCT.findall(t) if x not in pc and f"{float(x):.1f}" not in pc})
        out[p.name] = (bad_f, bad_p)
    return out


# --------------------------------------------------------------------- 3. links / path references
def link_check():
    results = []
    ignore_patterns = {l.strip() for l in Path(".gitignore").read_text().splitlines() if l.strip() and not l.startswith("#")}
    for p in FINAL_MD:
        t = strip_code(p.read_text())
        refs = [("link", m) for m in re.findall(r"\[[^\]]+\]\(([^)]+)\)", t)]
        refs += [("path", m) for m in re.findall(r"`([^`\s]+)`", t)
                 if re.search(r"(/|\.(md|csv|py|sql|json|pdf|log)$)", m) and not re.search(r"[*<>|~]", m) and not m.startswith("http")]
        for kind, ref in refs:
            ref_clean = ref.split("#")[0].rstrip("/")
            cands = [(p.parent / ref_clean)]
            if not ref_clean.startswith("."):
                cands.append(ROOT / ref_clean)
            ok = any(c.exists() for c in cands)
            if not ok and ref in ignore_patterns:
                results.append((p.name, kind, ref, "OK (.gitignore pattern quoted in text, not a file link)"))
                continue
            results.append((p.name, kind, ref, "OK" if ok else "MISSING"))
    return results


# --------------------------------------------------------------------- 4. CSV structure
def csv_check():
    from src.final_package import COLS
    raw = FINAL_CSV.read_bytes()
    problems = []
    try:
        raw.decode("utf-8")
    except UnicodeDecodeError:
        problems.append("not UTF-8")
    rows = list(csv.reader(raw.decode("utf-8").splitlines()))
    if rows[0] != COLS:
        problems.append(f"header mismatch {rows[0]}")
    widths = {len(r) for r in rows}
    if widths != {len(COLS)}:
        problems.append(f"inconsistent column counts {widths}")
    recs = list(csv.DictReader(FINAL_CSV.open()))
    ids = [r["Finding_ID"] for r in recs]
    if len(ids) != len(set(ids)):
        problems.append("duplicate Finding_ID")
    if not all(re.fullmatch(r"FND-\d{2}", i) for i in ids):
        problems.append("Finding_ID format")
    empties = [(r["Finding_ID"], c) for r in recs for c in COLS if not r[c].strip()]
    if empties:
        problems.append(f"empty cells {empties}")
    if any("\n" in v for r in recs for v in r.values()):
        problems.append("embedded newlines")
    if not all(re.search(r"\d", r["Observed_Value"]) for r in recs):
        problems.append("Observed_Value without a number")
    if not all(r["Confidence"].split()[0] in ("High", "Medium", "Low") for r in recs):
        problems.append("Confidence outside High/Medium/Low")
    srcfiles = {f for r in recs for f in re.findall(r"[\w.]+\.csv", r["Evidence_Source"])}
    missing_src = sorted(f for f in srcfiles if not (OUT / f).exists())
    if missing_src:
        problems.append(f"evidence files missing {missing_src}")
    return len(recs), len(COLS), problems


